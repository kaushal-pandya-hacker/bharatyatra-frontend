export async function seedPackages() {
  console.log('Seeding Real India Travel Packages into database...');
  for (const pkgData of PACKAGES_TO_SEED) {
    await prisma.package.upsert({
      where: { slug: pkgData.slug },
      update: pkgData,
      create: pkgData,
    });
  }
  console.log(`Successfully seeded ${PACKAGES_TO_SEED.length} packages.`);
}

if (require.main === module) {
  seedPackages()
    .catch((e) => {
      console.error(e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
